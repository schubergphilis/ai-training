/**
 * The checkpoint export check's logic (spec S03 "Checkpoint export"): the
 * built `dist/data/checkpoints.json` must list every checkpoint of every
 * lesson page, and nothing else. `checkCheckpoints` reports a problem when
 *
 * - the file is missing or is not JSON, or its `version` is not 1;
 * - a checkpoint tag in a lesson page has no item, or an item names a
 *   checkpoint no page has;
 * - an item lacks a required field or has one of the wrong type;
 * - an item's `concepts` is empty or names an id that no topic YAML defines;
 * - a `choice`, `scenario` or `multi-choice` item is guessable from a cue
 *   (guessability.mjs lists them), or its `guessable` exemption names a cue
 *   that does not trip;
 * - an item's `phase` is not `first`, `review` or `practice`, a `practice`
 *   alternate has no `first` item with the same objective in its lesson, a
 *   `review` alternate has no reviewable one, or a `review` alternate is
 *   not `reviewable` (spec S03 "Checkpoints": a `repair`, an honor-system
 *   `predict` or `review={false}` can't be asked in a review).
 *
 * It also returns `warnings`, which do not fail it: one line per lesson
 * with an objective that has fewer review alternates than reviewable
 * `first` items, and a total, so the content work on alternates can be
 * measured.
 *
 * The export is generated by src/pages/data/checkpoints.json.ts from the same
 * tag reader as the pages (src/lib/checkpoint-tags.ts, imported here too,
 * so the gate and the build read a tag the same way); this check reads the
 * built file back so a broken build step or a stale `dist/` shows up in CI.
 * `scripts/check-checkpoints.mjs` is the command-line entry; tests import this.
 */
import { existsSync, readFileSync } from 'node:fs';
import { citationSpans } from '../../plugins/citation-syntax.mjs';
import { KIND_OF_TAG, PHASES } from '../../src/lib/checkpoint-rules.ts';
import { checkpointTagsOfSource } from '../../src/lib/checkpoint-tags.ts';
import { setAsideCode } from '../../src/lib/plain-citations.ts';
import { allTopics, readAreaTree } from './area-tree.mjs';
import { lessonPages } from './data.mjs';
import { walkMdx } from './examples.mjs';
import { checkGuessability } from './guessability.mjs';

/** Field name to the `typeof` it must have. `context`, `options`, `answer` and `guessable` may be null and are not listed. */
export const REQUIRED = {
	id: 'string',
	lesson: 'string',
	kind: 'string',
	objective: 'string',
	stem: 'string',
	hint: 'string',
	reviewable: 'boolean',
	revision: 'number',
	phase: 'string',
};

/**
 * The alternate rules over the export items (spec S03 "Checkpoints").
 * Siblings are matched by objective within a lesson. `errors` for a
 * `practice` alternate without a `first` sibling, a `review` alternate
 * without a reviewable `first` sibling (the review page would never ask
 * it), and a `review` alternate that can't be asked in a review.
 * `warnings`, per lesson, for each objective with fewer gradable `review`
 * alternates than reviewable `first` checkpoints, because the rule is at
 * least one alternate per checkpoint and one alternate must not cover
 * several; plus a total line when any is short. Items without a string
 * `lesson`, `id` and `objective` are left to the field checks.
 */
export function checkAlternates(items) {
	const errors = [];
	const warnings = [];
	const valid = items.filter(
		(i) => typeof i?.lesson === 'string' && typeof i?.id === 'string' && typeof i?.objective === 'string',
	);
	const byLesson = new Map();
	for (const item of valid) {
		if (!byLesson.has(item.lesson)) byLesson.set(item.lesson, []);
		byLesson.get(item.lesson).push(item);
	}
	let short = 0;
	let reviewable = 0;
	for (const [lesson, list] of byLesson) {
		const first = list.filter((i) => i.phase === 'first');
		const reviewableFirst = first.filter((i) => i.reviewable === true);
		for (const item of list) {
			if (item.phase !== 'review' && item.phase !== 'practice') continue;
			const where = `${lesson}#${item.id}`;
			const siblings = (item.phase === 'review' ? reviewableFirst : first).filter(
				(i) => i.objective === item.objective,
			);
			if (siblings.length === 0)
				errors.push(
					item.phase === 'review'
						? `${where}: a review alternate needs a reviewable first checkpoint with objective ${JSON.stringify(item.objective)} in its lesson, or the review page never asks it`
						: `${where}: a practice alternate needs a first checkpoint with objective ${JSON.stringify(item.objective)} in its lesson`,
				);
			if (item.phase === 'review' && item.reviewable !== true)
				errors.push(
					`${where}: a review alternate must be gradable in a review (not a repair, an honor-system predict or review={false})`,
				);
		}
		const gaps = [];
		for (const objective of [...new Set(reviewableFirst.map((i) => i.objective))]) {
			const own = reviewableFirst.filter((i) => i.objective === objective).length;
			const alternates = list.filter(
				(i) => i.phase === 'review' && i.reviewable === true && i.objective === objective,
			).length;
			reviewable += own;
			if (alternates < own) {
				short += own - alternates;
				gaps.push(`${objective} (${own} reviewable, ${alternates} alternate${alternates === 1 ? '' : 's'})`);
			}
		}
		if (gaps.length)
			warnings.push(`${lesson}: fewer review alternates than reviewable checkpoints: ${gaps.join(', ')}`);
	}
	if (short) warnings.push(`${short} of ${reviewable} reviewable checkpoints are not matched by a review alternate`);
	return { errors, warnings };
}

/** Every concept id in the topic YAML under `dataDir` (site/src/data). */
export function conceptIds(dataDir) {
	return new Set(allTopics(readAreaTree(dataDir)).flatMap((t) => (t.concepts ?? []).map((c) => c.id)));
}

/**
 * The `id` of a checkpoint tag as the page uses it: a string written as
 * `id="..."`. `undefined` for a missing id, an `id={...}` expression or a
 * value that is not a string, which the export check reports as an error.
 * `live-lessons.mjs` uses the same guard, so the e2e specs and this check
 * agree on which tags have an id.
 * @param {{ attrs: Map<string, { value: unknown, expr: boolean }> }} tag
 * @returns {string | undefined}
 */
export function checkpointTagId(tag) {
	const id = tag.attrs.get('id');
	if (!id || id.expr || typeof id.value !== 'string') return undefined;
	return id.value;
}

/**
 * A stem's source with every `(@key)` citation and the spaces before it
 * removed, the words the learner reads: the page renders a citation as a
 * number, while the export spells it out as its source (plain-citations.ts).
 * Code is set aside first, as `plainCitations` does, so a `(@key)` in a code
 * span stays, since the page shows it as written.
 * @param {string} stem
 * @returns {string}
 */
export function stemWithoutCitations(stem) {
	const aside = setAsideCode(stem);
	let out = '';
	let last = 0;
	for (const { index, length } of citationSpans(aside.text)) {
		out += aside.text.slice(last, index).replace(/\s+$/, '');
		last = index + length;
	}
	return aside.restore(out + aside.text.slice(last));
}

/**
 * `<lesson>#<id>` for every checkpoint tag in every lesson page under
 * `contentDir`, read with the same reader the build uses, and in `stems`
 * each one's stem without citations (`stemWithoutCitations`), for the
 * `echo` cue. A tag the reader rejects fails the build first, so it is
 * reported here as an error rather than thrown.
 */
export function pageCheckpointIds(contentDir, dataDir) {
	const areaIds = new Set(readAreaTree(dataDir).areas.map((a) => a.dir));
	const lessons = lessonPages(contentDir, areaIds);
	const out = new Set();
	/** @type {Map<string, string>} */
	const stems = new Map();
	const errors = [];
	for (const p of walkMdx(contentDir)) {
		const lesson = p.slice(contentDir.length + 1).replace(/\.mdx$/, '');
		if (!lessons.has(lesson)) continue;
		try {
			for (const t of checkpointTagsOfSource(readFileSync(p, 'utf8'), lesson)) {
				const id = checkpointTagId(t);
				if (id === undefined) errors.push(`${lesson}: <${t.tag}> without an id="..."`);
				else {
					out.add(`${lesson}#${id}`);
					stems.set(`${lesson}#${id}`, stemWithoutCitations(t.stem));
				}
			}
		} catch (e) {
			errors.push(e.message);
		}
	}
	return { ids: out, stems, errors };
}

/**
 * Check the export at `file` against the pages under `contentDir` and the
 * data tree under `dataDir`. Returns `{ errors: string[], items: number,
 * exemptions: string[], warnings: string[] }`, where `exemptions` is one
 * line per `guessable` item with its reason and `warnings` the lines of
 * `checkAlternates`, both for the caller to print.
 */
export function checkCheckpoints(file, contentDir, dataDir) {
	const errors = [];
	const fail = (msg) => errors.push(msg);
	const none = { items: 0, exemptions: [], warnings: [] };
	if (!existsSync(file)) return { ...none, errors: [`${file} does not exist; run site-build first`] };
	let data;
	try {
		data = JSON.parse(readFileSync(file, 'utf8'));
	} catch (e) {
		return { ...none, errors: [`${file}: not JSON: ${e.message}`] };
	}
	if (data?.version !== 1) fail(`version is ${JSON.stringify(data?.version)}, expected 1`);
	if (!Array.isArray(data?.items)) return { ...none, errors: [...errors, 'no items list'] };

	const known = conceptIds(dataDir);
	const kinds = new Set(Object.values(KIND_OF_TAG));
	const { ids: expected, stems, errors: pageErrors } = pageCheckpointIds(contentDir, dataDir);
	errors.push(...pageErrors);
	const seen = new Set();
	for (const [i, item] of data.items.entries()) {
		const where =
			typeof item?.lesson === 'string' && typeof item?.id === 'string' ? `${item.lesson}#${item.id}` : `items[${i}]`;
		for (const [field, type] of Object.entries(REQUIRED)) {
			const actual = typeof item?.[field];
			if (actual !== type) fail(`${where}: ${field} must be a ${type}`);
		}
		for (const field of ['context', 'options', 'answer', 'guessable']) {
			if (!(field in (item ?? {}))) fail(`${where}: ${field} is missing (null when absent)`);
		}
		if (!kinds.has(item?.kind)) fail(`${where}: kind ${JSON.stringify(item?.kind)} is not a checkpoint kind`);
		if (typeof item?.phase === 'string' && !PHASES.includes(item.phase))
			fail(`${where}: phase ${JSON.stringify(item.phase)} is not one of ${PHASES.join(', ')}`);
		if (!Array.isArray(item?.concepts) || item.concepts.length === 0)
			fail(`${where}: concepts must list at least one id`);
		else
			for (const c of item.concepts)
				if (!known.has(c)) fail(`${where}: concept ${JSON.stringify(c)} is not in the topic YAML`);
		if (seen.has(where)) fail(`${where}: listed twice`);
		seen.add(where);
		if (where.includes('#') && !expected.has(where)) fail(`${where}: no lesson page has this checkpoint`);
	}
	for (const id of [...expected].sort()) {
		if (!seen.has(id)) fail(`${id}: checkpoint in the lesson page is missing from the export`);
	}
	// The `echo` cue reads the page's stem without citations; an item no page has keeps the export's stem.
	const guess = checkGuessability(
		data.items.filter((item) => typeof item?.lesson === 'string' && typeof item?.id === 'string'),
		(item) => stems.get(`${item.lesson}#${item.id}`) ?? (typeof item.stem === 'string' ? item.stem : ''),
	);
	errors.push(...guess.errors);
	const alternates = checkAlternates(data.items);
	errors.push(...alternates.errors);
	return { errors, items: data.items.length, exemptions: guess.exemptions, warnings: alternates.warnings };
}
